import os, json, re, zipfile, io
import streamlit as st
from dotenv import load_dotenv
from groq import Groq

load_dotenv()
st.set_page_config(page_title="Multi-Agent Coder", page_icon="🧑‍💻")
st.title("🧑‍💻 Multi-Agent Coding Assistant")
prompt = st.text_area("Describe the application you want to build", "Build a responsive calculator web app.")
if st.button("Generate project"):
    if not os.getenv("GROQ_API_KEY"):
        st.error("Add GROQ_API_KEY to .env first.")
    elif not prompt.strip():
        st.warning("Describe your project.")
    else:
        client = Groq(api_key=os.getenv("GROQ_API_KEY"))
        with st.spinner("Planner and Architect are preparing the file plan..."):
            plan_msg = client.chat.completions.create(
                model=os.getenv("GROQ_MODEL","llama-3.3-70b-versatile"),
                messages=[
                    {"role":"system","content":"You are the Planner and Architect agents. Return ONLY valid JSON: {\"summary\":\"...\",\"files\":[{\"path\":\"index.html\",\"purpose\":\"...\"}]}. Create a small safe project with at most 8 files. Paths must be relative; no .., absolute paths, secrets, or executable install scripts."},
                    {"role":"user","content":prompt}
                ], temperature=0.2
            ).choices[0].message.content
        try:
            match = re.search(r"\{.*\}", plan_msg, re.S)
            plan = json.loads(match.group(0))
            st.subheader("Planner / Architect output")
            st.write(plan.get("summary",""))
            st.json(plan)
            generated = {}
            for item in plan.get("files", [])[:8]:
                path = item.get("path","").replace("\\","/")
                if path.startswith("/") or ".." in path.split("/") or not path:
                    continue
                with st.spinner(f"Coder agent: {path}"):
                    code = client.chat.completions.create(
                        model=os.getenv("GROQ_MODEL","llama-3.3-70b-versatile"),
                        messages=[
                            {"role":"system","content":"Generate only the complete file contents. No markdown fences, no explanation. Follow the requested purpose. Never include secrets."},
                            {"role":"user","content":f"Project request: {prompt}\nFile path: {path}\nPurpose: {item.get('purpose','')}"}
                        ], temperature=0.2
                    ).choices[0].message.content
                    code = re.sub(r"^```[a-zA-Z0-9_-]*\s*|\s*```$", "", code.strip())
                    generated[path] = code
            if not generated:
                st.error("No safe files were generated.")
            else:
                st.success(f"Generated {len(generated)} files.")
                for path, code in generated.items():
                    with st.expander(path):
                        st.code(code, language=path.rsplit(".",1)[-1])
                buffer = io.BytesIO()
                with zipfile.ZipFile(buffer,"w",zipfile.ZIP_DEFLATED) as z:
                    for path, code in generated.items():
                        z.writestr(path,code)
                    z.writestr("README.txt", "Generated by the Multi-Agent Coding Assistant. Review all code before running.")
                st.download_button("Download generated project ZIP", buffer.getvalue(), "generated_project.zip", "application/zip")
        except Exception as e:
            st.error(f"Could not parse the agent plan: {e}")
